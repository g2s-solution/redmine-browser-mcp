import { chmodSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { extensionIdFromKey } from "../../shared/extensionId.js";

export const HOST_NAME = "com.redmine_bridge.daemon";

export interface InstallOptions {
  repoDir: string;
  nodePath: string;
  home: string;
  platform: NodeJS.Platform;
  readOnly?: boolean;
  port?: number;
  extensionId?: string;
}

const BROWSERS: Record<string, string[]> = {
  linux: [".config/google-chrome", ".config/chromium", ".config/BraveSoftware/Brave-Browser", ".config/microsoft-edge"],
  darwin: [
    "Library/Application Support/Google/Chrome",
    "Library/Application Support/Chromium",
    "Library/Application Support/BraveSoftware/Brave-Browser",
    "Library/Application Support/Microsoft Edge",
  ],
};

export function readExtensionId(repoDir: string): string {
  const manifest = JSON.parse(readFileSync(join(repoDir, "extension", "manifest.json"), "utf8"));
  if (!manifest.key) throw new Error("extension/manifest.json has no key, so the extension id is not stable");
  return extensionIdFromKey(manifest.key);
}

export function launcherPath(home: string): string {
  return join(home, ".local", "share", "redmine-mcp", "native-host.sh");
}

export function launcherScript(o: InstallOptions): string {
  for (const p of [o.repoDir, o.nodePath]) {
    if (/["\\$`\n]/.test(p)) throw new Error(`path contains a character that cannot be used in the launcher: ${p}`);
  }
  const env = [o.readOnly ? "export READ_ONLY=1" : "", o.port ? `export REDMINE_MCP_PORT=${o.port}` : ""].filter(
    Boolean,
  );
  return [
    "#!/bin/sh",
    "# Generated by npm run install-host; Chrome starts this file as the native messaging host.",
    ...env,
    `cd "${o.repoDir}" || exit 1`,
    `exec "${o.nodePath}" "${o.repoDir}/node_modules/tsx/dist/cli.mjs" daemon/src/native-host.ts`,
    "",
  ].join("\n");
}

export function hostManifest(extensionId: string, path: string): object {
  return {
    name: HOST_NAME,
    description: "Redmine MCP bridge daemon",
    path,
    type: "stdio",
    allowed_origins: [`chrome-extension://${extensionId}/`],
  };
}

export function manifestDirs(home: string, platform: NodeJS.Platform): string[] {
  const roots = BROWSERS[platform];
  if (!roots)
    throw new Error(`native host installation is not supported on ${platform} yet (Windows needs a registry entry)`);
  return roots
    .map((r) => join(home, r))
    .filter((dir) => existsSync(dir))
    .map((dir) => join(dir, "NativeMessagingHosts"));
}

export function install(o: InstallOptions): { launcher: string; manifests: string[]; extensionId: string } {
  const extensionId = o.extensionId ?? readExtensionId(o.repoDir);
  if (!existsSync(join(o.repoDir, "node_modules", "tsx", "dist", "cli.mjs")))
    throw new Error("run npm ci first (node_modules/tsx is missing)");
  const dirs = manifestDirs(o.home, o.platform);
  if (dirs.length === 0)
    throw new Error("no Chrome, Chromium, Brave or Edge profile directory found; start the browser once first");
  const launcher = launcherPath(o.home);
  mkdirSync(dirname(launcher), { recursive: true });
  writeFileSync(launcher, launcherScript(o));
  chmodSync(launcher, 0o755);
  const manifests = dirs.map((dir) => {
    mkdirSync(dir, { recursive: true });
    const file = join(dir, `${HOST_NAME}.json`);
    writeFileSync(file, JSON.stringify(hostManifest(extensionId, launcher), null, 2) + "\n");
    return file;
  });
  return { launcher, manifests, extensionId };
}

export function uninstall(home: string, platform: NodeJS.Platform): string[] {
  const removed: string[] = [];
  for (const dir of manifestDirs(home, platform)) {
    const file = join(dir, `${HOST_NAME}.json`);
    if (existsSync(file)) {
      rmSync(file);
      removed.push(file);
    }
  }
  rmSync(launcherPath(home), { force: true });
  return removed;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const repoDir = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
  const base = { repoDir, nodePath: process.execPath, home: homedir(), platform: process.platform };
  try {
    if (args.includes("--uninstall")) {
      const removed = uninstall(base.home, base.platform);
      console.log(removed.length ? `removed:\n${removed.join("\n")}` : "nothing to remove");
    } else {
      const portArg = args.indexOf("--port");
      const r = install({
        ...base,
        readOnly: args.includes("--read-only"),
        port: portArg >= 0 ? Number(args[portArg + 1]) : undefined,
      });
      console.log(
        `native host installed for extension ${r.extensionId}\nlauncher: ${r.launcher}\n${r.manifests.join("\n")}`,
      );
      console.log(
        "Reload the extension in chrome://extensions; the popup then connects without starting the daemon yourself.",
      );
    }
  } catch (e) {
    console.error(e instanceof Error ? e.message : String(e));
    process.exit(1);
  }
}
